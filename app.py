    if wo == ta:
        return 0
    elif sheng[wo] == ta:
        return 1
    elif ke[wo] == ta:
        return -1
    elif sheng[ta] == wo:
        return -2
    elif ke[ta] == wo:
        return 2
    else:
        return 0

